function signFor(month, day) {
const capricorn = SIGNS.find(s => s.key === "capricorn");
// Capricorn straddles New Year, so it can't be found by a simple cutoff walk.
if ((month === 12 && day >= 22) || (month === 1 && day <= 19)) return capricorn;

const ordered = [...SIGNS].filter(s => s.key !== "capricorn")
.sort((a, b) => (b.start[0] - a.start[0]) || (b.start[1] - a.start[1]));
for (const s of ordered) {
if (month > s.start[0] || (month === s.start[0] && day >= s.start[1])) return s;
}
return capricorn;
}

function hash(str) {
let h = 2166136261;
for (let i = 0; i < str.length; i++) {
h ^= str.charCodeAt(i);
h = Math.imul(h, 16777619);
}
return h >>> 0;
}

function rng(seed) {
let a = seed;
return () => {
a |= 0; a = (a + 0x6D2B79F5) | 0;
let t = Math.imul(a ^ (a >>> 15), 1 | a);
t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
}

